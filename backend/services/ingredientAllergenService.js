// [통일 이름, 정규식] — 화면에 나오는 순서
const RULES = [
  ["계란", /계란|달걀|전란|난백|난황|난각|유정란|메추리알|마요네즈|알류|난류/],
  [
    "우유",
    /우유|분유|유크림|생크림|유청|카제인|유당|연유|발효유|요구르트|요거트|치즈|마스카포네|(?<!코코아|카카오|땅콩|시어|코코넛|아몬드)버터/,
  ],
  ["메밀", /메밀|(?<!약)모밀/],
  ["땅콩", /땅콩|피넛/],
  [
    "대두",
    /대두|두유|두부|콩기름|콩가루|콩나물|검정콩|검은콩|흰콩|노란콩|약콩|서리태|백태|메주|간장|된장|청국장/,
  ],
  ["밀", /(?<![호메모])밀(?!크|감|납|리|씨)|소맥|글루텐|듀럼|세몰리나/],
  ["고등어", /고등어/],
  ["게", /^게$|게살|꽃게|대게|홍게|게장|크랩/],
  ["새우", /새우/],
  ["돼지고기", /돼지(?!감자)|돈육|돈지|라드/],
  ["복숭아", /복숭아/],
  ["토마토", /(?<!나무)토마토/],
  ["아황산류", /아황산|이산화황/],
  ["호두", /호두/],
  ["닭고기", /닭|계육/],
  ["쇠고기", /쇠고기|소고기|우육|우지/],
  ["오징어", /오징어/],
  ["조개류", /(?<![둥덩])굴(?!레)|홍합|전복|바지락|조개|가리비|재첩|꼬막/],
  ["잣", /잣/],
  ["헤이즐넛", /헤이즐넛|개암/],
  ["산양유", /산양유|산양분유|염소젖/],
];

const SEPARATORS = /[[\](){}<>,，、:：/]/;
const FLAVOR = /향(료|분말|오일)?$|맛분말$/;

/**
 * @param {string[]} names - 원재료 이름 (DB 원재료 또는 라벨에서 읽은 원재료)
 * @returns {string[]} 찾은 알레르기 통일 이름 (중복 없이, RULES 순서)
 */
function findAllergensInIngredients(names) {
  const pieces = [];
  for (const name of names ?? []) {
    const text = String(name);
    if (text.includes("또는")) continue;
    for (const piece of text.split(SEPARATORS)) {
      const core = piece.replace(/\s+/g, "");
      if (core && !FLAVOR.test(core)) pieces.push(core);
    }
  }
  return RULES.filter(([, pattern]) => pieces.some((p) => pattern.test(p))).map(([name]) => name);
}

module.exports = { findAllergensInIngredients };
